"""Turn a hand-filled CSV into a .json file and a .py file the team can import.

Usage (from inside the browse folder):
    python make_data.py instruments

Reads  browse/<name>.csv
Writes processed/<name>.json  and  processed/<name>.py
"""
import csv
import json
import pprint
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "processed"
OUT.mkdir(exist_ok=True)


def convert(value):
    """
    '' -> None, 
    '12' -> 12, 
    '1.5' -> 1.5, 
    anything else stays text.
    """
    value = value.strip()
    if value == "":
        return None
    for kind in (int, float):
        try:
            return kind(value)
        except ValueError:
            pass
    return value


def parse_flags(text):
    """
    'mass=REAL;power=DERIVED' -> {'mass': 'REAL', 'power': 'DERIVED'}
    """
    flags = {}
    for part in (text or "").split(";"):
        if "=" in part:
            key, val = part.split("=", 1)
            flags[key.strip()] = val.strip().upper()
    return flags


def main(name):
    src = HERE / f"{name}.csv"
    rows, warnings = [], []
    with open(src, newline="", encoding="utf-8-sig") as f:
        for line_no, raw in enumerate(csv.DictReader(f), start=2):
            row = {k: convert(v or "") for k, v in raw.items() if k}
            if row.get("flags") is not None:
                row["flags"] = parse_flags(raw.get("flags", ""))
            label = row.get("id") or f"line {line_no}"
            has_number = any(isinstance(v, (int, float)) for v in row.values())
            if has_number and not row.get("source_url"):
                warnings.append(f"{label}: has numbers but no source_url")
            if has_number and not row.get("retrieved"):
                warnings.append(f"{label}: has numbers but no retrieved date")
            if has_number and not row.get("flags"):
                warnings.append(f"{label}: has numbers but no flags")
            if "PROTOTYPE" in (row.get("flags") or {}).values():
                warnings.append(f"{label}: still has a PROTOTYPE value")
            rows.append(row)

    (OUT / f"{name}.json").write_text(json.dumps(rows, indent=2, ensure_ascii=False), encoding="utf-8")
    header = (f'"""AUTO-GENERATED from browse/{name}.csv by make_data.py.\n'
              f'Do not edit this file. Edit the CSV, then run: python make_data.py {name}\n"""\n\n')
    (OUT / f"{name}.py").write_text(header + f"{name.upper()} = " + pprint.pformat(rows, sort_dicts=False) + "\n", encoding="utf-8")

    print(f"OK: {len(rows)} rows -> processed/{name}.json and processed/{name}.py")
    for w in warnings:
        print("  WARNING:", w)


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit("Usage: python make_data.py <csv-name-without-.csv>")
    main(sys.argv[1])